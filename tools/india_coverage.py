#!/usr/bin/env python3
"""India checklist: every dynasty and state in South Asia that Wikidata knows, and how much of its time the map draws.

Uses the cached Wikidata answer from tools/gaps.py (data/wikidata-states.json: states, kingdoms, empires, sultanates,
dynasties, princely states… with a start date, a location and 8+ Wikipedia editions). For each one in South Asia it
finds the map's realms with the same name (Cliopatria by Wikidata id or name, reconstruction layers by name, loosely:
"Madurai Sultanate (Ma'bar)" = "Madurai Sultanate") and measures the share of its years they cover.
Writes content/factcheck/india-dynasties.md. Run: python3 -I tools/india_coverage.py
"""
import glob, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from gaps import core, year  # same loose name matching as the audit

IN_SA = lambda x, y: 60 <= x <= 98 and 5 <= y <= 37.5
MODERN = re.compile(r"republic|dominion|province|presidency|agency|division|union territory|state of |pakistan|bangladesh|afghanistan|burma|myanmar|ceylon|sri lanka", re.I)


def main():
    rows = json.load(open(os.path.join(ROOT, "data", "wikidata-states.json")))["results"]["bindings"]
    idx = json.load(open(os.path.join(ROOT, "public", "data", "clio", "index.json")))["realms"]
    spans = {}  # core name -> list of [from, to] the map draws
    by_q = {}
    for n, r in idx.items():
        sp = [[a, b] for a, b, _ in r["tl"]]
        spans.setdefault(core(n), []).extend(sp)
        if r.get("wd"): by_q.setdefault(r["wd"], []).extend(sp)
    for p in glob.glob(os.path.join(ROOT, "content", "supplements", "*.json")):
        sup = json.load(open(p))
        for rg in sup.get("regions", []):
            spans.setdefault(core(rg["name"]), []).append([rg.get("from", sup["from"]), rg.get("to", sup["to"])])
            if rg.get("key"): spans.setdefault(core(rg["key"]), []).append([rg.get("from", sup["from"]), rg.get("to", sup["to"])])
    # content/realm-aliases.json: {"Q-id": {"names": [map realm or layer names], "why": "..."}} for states drawn under another name
    ap = os.path.join(ROOT, "content", "realm-aliases.json")
    aliases = json.load(open(ap)) if os.path.exists(ap) else {}
    verdicts = {}
    vp = os.path.join(ROOT, "content", "india-verdicts.json")  # {"Q-id": "reason it needs no drawing (vassal years, group, dates…)"}
    if os.path.exists(vp): verdicts = json.load(open(vp))
    items = {}
    for r in rows:
        q = r["item"]["value"].rsplit("/", 1)[1]
        label = r.get("itemLabel", {}).get("value", q)
        m = re.match(r"Point\(([-\d.]+) ([-\d.]+)\)", r.get("coord", {}).get("value", ""))
        s, e = year(r.get("start", {}).get("value")), year(r.get("end", {}).get("value"))
        if not m or s is None or re.fullmatch(r"Q\d+", label) or not IN_SA(float(m.group(1)), float(m.group(2))):
            continue
        e = e if e is not None else 2024
        if e < -1500 or s > 1950: continue
        it = items.setdefault(q, {"q": q, "label": label, "from": s, "to": e, "sl": 0})
        it["sl"] = max(it["sl"], int(r["sl"]["value"]))
    out = []
    for it in items.values():
        drawn = by_q.get(it["q"], []) + spans.get(core(it["label"]), [])
        for n in aliases.get(it["q"], {}).get("names", []): drawn += spans.get(core(n), [])
        it["verdict"] = verdicts.get(it["q"])
        a, b = it["from"], min(it["to"], 2024)
        years = set()
        for f, t in drawn:
            years.update(range(max(a, f), min(b, t) + 1))
        share = len(years) / max(1, b - a + 1)
        it["share"] = share
        it["drawn"] = drawn
        it["modern"] = bool(MODERN.search(it["label"])) and it["from"] > 1800
        out.append(it)
    out.sort(key=lambda i: (i["from"], i["label"]))
    full = [i for i in out if i["share"] >= 0.9]
    part = [i for i in out if 0.05 <= i["share"] < 0.9]
    none = [i for i in out if i["share"] < 0.05]
    path = os.path.join(ROOT, "content", "factcheck", "india-dynasties.md")
    with open(path, "w") as fh:
        fh.write("# India checklist: dynasties and states, and how much of their time the map draws\n\n"
                 "Generated by tools/india_coverage.py from Wikidata (South Asia, 1500 BCE–1950, 8+ Wikipedia editions). "
                 "Coverage = share of the years it existed that a realm of the same name is drawn (Cliopatria or a "
                 "reconstruction layer). 'Missing' can also mean the map draws it under a different name (e.g. a dynasty "
                 "drawn as its kingdom), or that it is a modern administrative unit: check before drawing.\n\n")
        fh.write(f"**{len(out)} dynasties and states** · drawn for most of their time: {len(full)} · partly: {len(part)} · "
                 f"missing: {len(none)} ({sum(1 for i in none if i['modern'])} of them modern units or regimes)\n")
        for title, lst in (("Missing", [i for i in none if not i["modern"]]), ("Partly drawn", part),
                           ("Missing: modern units and regimes (usually drawn under another name)", [i for i in none if i["modern"]]),
                           ("Drawn for most of their time", full)):
            fh.write(f"\n## {title} ({len(lst)})\n\n| Dynasty or state | Years | Drawn | Wikipedia editions | Wikidata |\n|---|---|---|---|---|\n")
            for i in lst:
                fh.write(f"| {i['label']} | {i['from']}–{i['to']} | {round(100 * i['share'])}%{' · ' + i['verdict'] if i.get('verdict') else ''} | {i['sl']} | [{i['q']}](https://www.wikidata.org/wiki/{i['q']}) |\n")
    print(len(out), "dynasties/states:", len(full), "full,", len(part), "partly,", len(none), "missing ->", os.path.relpath(path, ROOT))


if __name__ == "__main__":
    main()
