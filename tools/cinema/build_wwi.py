# ---------------------------------------------------------------- helpers
def resample(pts, n):
    """Resample a polyline to n points evenly spaced by arc length (keeps ends)."""
    d = [0.0]
    for a, b in zip(pts, pts[1:]):
        d.append(d[-1] + math.hypot(b[0] - a[0], b[1] - a[1]))
    L = d[-1]
    out = []
    j = 0
    for i in range(n):
        t = L * i / (n - 1)
        while j < len(d) - 2 and d[j + 1] < t:
            j += 1
        seg = d[j + 1] - d[j] or 1e-12
        f = (t - d[j]) / seg
        a, b = pts[j], pts[j + 1]
        out.append((a[0] + (b[0] - a[0]) * f, a[1] + (b[1] - a[1]) * f))
    return out

def rnd(pts, k=3):
    return [[round(x, k), round(y, k)] for x, y in pts]

