def largest(g):
    if g.is_empty:
        return None
    if isinstance(g, Polygon):
        return g
    polys = [p for p in getattr(g, 'geoms', []) if isinstance(p, Polygon)]
    return max(polys, key=lambda p: p.area) if polys else None

def ring_of(g, n, anchor, k=3):
    g = g.buffer(-0.04, join_style=2).buffer(0.04, join_style=2)   # drop slivers left by approximate river/border tracing
    p = largest(g)
    if p is None or p.area < 0.002:
        return None
    p = p.simplify(0.01, preserve_topology=True)
    pts = list(p.exterior.coords)[:-1]
    # counter-clockwise
    area2 = sum(pts[i][0] * pts[(i + 1) % len(pts)][1] - pts[(i + 1) % len(pts)][0] * pts[i][1] for i in range(len(pts)))
    if area2 < 0:
        pts = pts[::-1]
    i0 = min(range(len(pts)), key=lambda i: (pts[i][0] - anchor[0]) ** 2 + (pts[i][1] - anchor[1]) ** 2)
    pts = pts[i0:] + pts[:i0]
    pts = resample(pts + [pts[0]], n + 1)[:-1]
    out = rnd(pts, k)
    out.append(out[0])
    return out

